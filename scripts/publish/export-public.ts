/** Builds a public snapshot directory (no git history) from HEAD, without the private approved lesson text.
 * Usage: node scripts/publish/export-public.ts <new-or-empty-output-dir>
 * It never pushes, never creates a remote, and refuses to write into a non-empty directory. */
import { spawnSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('../../', import.meta.url));
/** Repo-relative paths that carry the paid lesson text. Keep in sync with the leak scan below. */
export const PRIVATE_PATHS = ['fixtures/eval/approved/lessons', 'test/replay/approved-answer-map.json'] as const;
const WINDOW = 50;
function walk(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? (e.name === '.git' || e.name === 'node_modules' ? [] : walk(join(dir, e.name))) : [join(dir, e.name)]);
}
/** 50-char windows of every long lesson line. A public file containing any window leaks lesson text. */
export function lessonShingles(lessons: readonly string[]): Set<string> {
  const out = new Set<string>();
  for (const text of lessons) for (const raw of text.split('\n')) { const line = raw.trim(); if (line.length >= WINDOW) for (let i = 0; i + WINDOW <= line.length; i += 25) out.add(line.slice(i, i + WINDOW)); }
  return out;
}
export function findLessonLeaks(dir: string, shingles: ReadonlySet<string>): string[] {
  const leaks: string[] = [];
  for (const file of walk(dir)) {
    if (statSync(file).size > 5_000_000) continue;
    let text: string; try { text = readFileSync(file, 'utf8'); } catch { continue; }
    for (const s of shingles) if (text.includes(s)) { leaks.push(file.slice(dir.length + 1)); break; }
  }
  return leaks;
}
export function exportPublic(out: string): { files: number; shingles: number } {
  if (existsSync(out) && readdirSync(out).length > 0) throw new Error('OUTPUT_DIR_NOT_EMPTY');
  const lessonsDir = join(root, PRIVATE_PATHS[0]);
  const lessons = readdirSync(lessonsDir).filter((f) => f.endsWith('.md')).map((f) => readFileSync(join(lessonsDir, f), 'utf8'));
  if (lessons.length === 0) throw new Error('NO_LESSONS_TO_SCAN_FOR');
  const shingles = lessonShingles(lessons);
  if (shingles.size === 0) throw new Error('NO_SHINGLES_BUILT');
  mkdirSync(out, { recursive: true });
  const archive = spawnSync('git', ['-C', root, 'archive', '--format=tar', 'HEAD'], { maxBuffer: 1 << 28 });
  if (archive.status !== 0) throw new Error('GIT_ARCHIVE_FAILED');
  const untar = spawnSync('tar', ['-x', '-C', out], { input: archive.stdout });
  if (untar.status !== 0) throw new Error('TAR_EXTRACT_FAILED');
  for (const p of PRIVATE_PATHS) rmSync(join(out, p), { recursive: true, force: true });
  const leaks = findLessonLeaks(out, shingles);
  if (leaks.length > 0) throw new Error(`LESSON_TEXT_STILL_PRESENT: ${leaks.join(', ')}`);
  writeFileSync(join(out, 'PUBLIC_EXPORT'), 'Public snapshot: approved lesson text removed (tests that need it are skipped explicitly). Generated by scripts/publish/export-public.ts.\n');
  return { files: walk(out).length, shingles: shingles.size };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const out = process.argv[2]; if (!out) throw new Error('USAGE: export-public.ts <output-dir>');
  console.log(JSON.stringify(exportPublic(out)));
}
